#!/usr/bin/env python3
"""
Regenerate vendor_ranges.tsv from the crawler IP lists vendors publish, then
write the three copies (Django and both Go services embed theirs, so a change
ships with a deploy). A range we miss turns a real crawler into 'Spoofed X',
so a list that fails to load or shrinks by half stops the run with nothing
written.

    python3 deploy/refresh_vendor_ranges.py
"""
import ipaddress
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COPIES = [
    ROOT / 'acpwb/apps/core/vendor_ranges.tsv',
    ROOT / 'acpwb_go/botclassify/vendor_ranges.tsv',
    ROOT / 'acpwb_edge/botclassify/vendor_ranges.tsv',
]

GOOGLE = 'https://developers.google.com/static'
SOURCES = {
    'Anthropic': ['https://claude.com/crawling/bots.json'],
    'Bing': ['https://www.bing.com/toolbox/bingbot.json'],
    'DuckDuckGo': ['https://duckduckgo.com/duckduckbot.json', 'https://duckduckgo.com/duckassistbot.json'],
    'Google': [
        f'{GOOGLE}/search/apis/ipranges/googlebot.json',
        f'{GOOGLE}/search/apis/ipranges/special-crawlers.json',
        f'{GOOGLE}/search/apis/ipranges/user-triggered-fetchers.json',
        f'{GOOGLE}/search/apis/ipranges/user-triggered-fetchers-google.json',
        f'{GOOGLE}/crawling/ipranges/user-triggered-agents.json',
    ],
    'OpenAI': [
        'https://openai.com/gptbot.json',
        'https://openai.com/searchbot.json',
        'https://openai.com/chatgpt-user.json',
        'https://openai.com/adsbot.json',
    ],
    'Perplexity': ['https://www.perplexity.ai/perplexitybot.json', 'https://www.perplexity.ai/perplexity-user.json'],
}


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(req, timeout=30) as resp:
        prefixes = json.load(resp)['prefixes']
    nets = [ipaddress.ip_network(p.get('ipv4Prefix') or p['ipv6Prefix']) for p in prefixes]
    if not nets:
        raise ValueError(f'{url}: no prefixes')
    return nets


def collapsed(nets):
    """Sorted, non-overlapping networks: classifiers binary-search these."""
    return [
        net for version in (4, 6)
        for net in ipaddress.collapse_addresses(n for n in nets if n.version == version)
    ]


def current_counts():
    counts = {}
    if COPIES[0].exists():
        for line in COPIES[0].read_text().splitlines():
            if line and not line.startswith('#'):
                vendor = line.split('\t')[0]
                counts[vendor] = counts.get(vendor, 0) + 1
    return counts


def main():
    old = current_counts()
    lines = ['# Generated by deploy/refresh_vendor_ranges.py. Do not edit.']
    for vendor, urls in SOURCES.items():
        nets = collapsed([net for url in urls for net in fetch(url)])
        if len(nets) < old.get(vendor, 0) / 2:
            sys.exit(f'{vendor}: {len(nets)} ranges, was {old[vendor]}. Nothing written.')
        print(f'{vendor}: {len(nets)} ranges (was {old.get(vendor, 0)})')
        lines += [f'{vendor}\t{net}' for net in nets]
    text = '\n'.join(lines) + '\n'
    for path in COPIES:
        path.write_text(text)


if __name__ == '__main__':
    main()
